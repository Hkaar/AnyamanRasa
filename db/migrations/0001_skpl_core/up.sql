-- Core schema from SKPL-IFPAGI01 §4.2.5–4.2.6 (TAB-5, TAB-6).
-- Design-driven extensions live in 0002_design_extensions.

create type recipe_difficulty as enum ('mudah', 'sedang', 'sulit');
create type recipe_status as enum ('draft', 'published', 'archived');
create type node_type as enum ('recipe', 'ingredient');
-- SKPL-F-10.1 minimum relationship types.
create type relation_type as enum (
  'uses',
  'variation_of',
  'substitute_for',
  'similar_to',
  'inspired_by',
  'pairs_with'
);

create table users (
  id uuid primary key default gen_random_uuid(),
  name varchar(100) not null check (length(trim(name)) > 0),
  email varchar(255) not null unique,
  password varchar(255) not null,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table roles (
  id integer primary key,
  name varchar(50) not null unique
);

create table user_roles (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references users(id) on delete cascade,
  role_id integer not null references roles(id) on delete cascade,
  unique (user_id, role_id)
);

create table recipes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references users(id) on delete cascade,
  title varchar(255) not null check (length(trim(title)) > 0),
  description text not null default '',
  image_url text,
  prep_time_minutes integer not null default 0 check (prep_time_minutes >= 0),
  cook_time_minutes integer not null default 0 check (cook_time_minutes >= 0),
  difficulty recipe_difficulty not null,
  -- Ordered array of { "text": string, "title"?: string, "minutes"?: number }.
  steps jsonb not null default '[]'::jsonb check (jsonb_typeof(steps) = 'array'),
  -- Required for variations (SKPL-F-07.3); null for original recipes.
  change_summary text,
  status recipe_status not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index recipes_user_id_idx on recipes (user_id);
create index recipes_status_created_at_idx on recipes (status, created_at desc);

create table ingredients (
  id uuid primary key default gen_random_uuid(),
  name varchar(150) not null check (length(trim(name)) > 0),
  description text not null default ''
);

create unique index ingredients_name_unique_idx on ingredients (lower(name));

create table recipe_ingredients (
  id uuid primary key default gen_random_uuid(),
  recipe_id uuid not null references recipes(id) on delete cascade,
  ingredient_id uuid not null references ingredients(id) on delete restrict,
  quantity decimal(10, 2) check (quantity is null or quantity > 0),
  unit varchar(50),
  note varchar(255),
  unique (recipe_id, ingredient_id)
);

create index recipe_ingredients_ingredient_id_idx on recipe_ingredients (ingredient_id);

create table categories (
  id integer generated by default as identity primary key,
  name varchar(100) not null unique
);

create table recipe_categories (
  id uuid primary key default gen_random_uuid(),
  recipe_id uuid not null references recipes(id) on delete cascade,
  category_id integer not null references categories(id) on delete cascade,
  unique (recipe_id, category_id)
);

create index recipe_categories_category_id_idx on recipe_categories (category_id);

-- Explicit, typed relationships between graph nodes. Endpoints are polymorphic
-- (recipe | ingredient), so referential integrity is enforced by the checks and
-- cleanup triggers below instead of foreign keys.
create table node_relations (
  id uuid primary key default gen_random_uuid(),
  source_type node_type not null,
  source_id uuid not null,
  target_type node_type not null,
  target_id uuid not null,
  relation_type relation_type not null,
  label varchar(255),
  created_by uuid references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint node_relations_no_self check (not (source_type = target_type and source_id = target_id)),
  constraint node_relations_endpoint_types check (
    case relation_type
      when 'uses' then source_type = 'recipe' and target_type = 'ingredient'
      when 'variation_of' then source_type = 'recipe' and target_type = 'recipe'
      when 'similar_to' then source_type = 'recipe' and target_type = 'recipe'
      when 'inspired_by' then source_type = 'recipe' and target_type = 'recipe'
      when 'substitute_for' then source_type = 'ingredient' and target_type = 'ingredient'
      when 'pairs_with' then source_type = target_type
    end
  ),
  unique (source_type, source_id, target_type, target_id, relation_type)
);

create index node_relations_source_idx on node_relations (source_type, source_id);
create index node_relations_target_idx on node_relations (target_type, target_id);
-- A variation has exactly one source recipe (SKPL-F-07.2).
create unique index node_relations_single_parent_idx
  on node_relations (source_id)
  where relation_type = 'variation_of';

create function node_relations_endpoint_exists() returns trigger as $$
begin
  if new.source_type = 'recipe' and not exists (select 1 from recipes where id = new.source_id)
    or new.source_type = 'ingredient' and not exists (select 1 from ingredients where id = new.source_id)
  then
    raise exception 'node_relations source % % does not exist', new.source_type, new.source_id
      using errcode = 'foreign_key_violation';
  end if;
  if new.target_type = 'recipe' and not exists (select 1 from recipes where id = new.target_id)
    or new.target_type = 'ingredient' and not exists (select 1 from ingredients where id = new.target_id)
  then
    raise exception 'node_relations target % % does not exist', new.target_type, new.target_id
      using errcode = 'foreign_key_violation';
  end if;
  return new;
end;
$$ language plpgsql;

create trigger node_relations_endpoint_exists
  before insert or update on node_relations
  for each row execute function node_relations_endpoint_exists();

create function node_relations_cleanup() returns trigger as $$
begin
  delete from node_relations
  where (source_type = tg_argv[0]::node_type and source_id = old.id)
     or (target_type = tg_argv[0]::node_type and target_id = old.id);
  return old;
end;
$$ language plpgsql;

create trigger recipes_node_relations_cleanup
  after delete on recipes
  for each row execute function node_relations_cleanup('recipe');

create trigger ingredients_node_relations_cleanup
  after delete on ingredients
  for each row execute function node_relations_cleanup('ingredient');
