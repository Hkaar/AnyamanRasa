// Regenerates app/ui/icon-data.ts from the `lucide` package with only the icons the design uses.
// Usage: node --import remix/node-tsx scripts/generate-icons.ts
import { writeFile } from 'node:fs/promises'
import * as lucide from 'lucide'

const names = [
  'arrow-right', 'arrow-left', 'arrow-up', 'arrow-down', 'arrow-up-right', 'arrow-left-right',
  'x', 'check', 'plus', 'minus', 'search', 'search-x', 'menu', 'chevron-down', 'chevron-up',
  'chevron-left', 'chevron-right', 'clock-3', 'signal', 'user-round', 'users-round', 'users', 'tag',
  'leaf', 'carrot', 'compass', 'bookmark', 'book-open', 'book-marked', 'git-branch', 'git-compare',
  'git-compare-arrows', 'clipboard-list', 'lightbulb', 'share-2', 'house', 'shopping-basket',
  'settings', 'log-out', 'circle-check', 'circle-dashed', 'circle-alert', 'sparkles', 'trash-2',
  'sliders-horizontal', 'list', 'maximize-2', 'hand', 'rotate-ccw', 'mouse-pointer-click',
  'locate-fixed', 'refrigerator', 'info', 'eye', 'eye-off', 'image-plus', 'grip-vertical', 'pencil',
  'equal', 'download', 'layout-grid', 'flag', 'ellipsis', 'file', 'archive', 'waypoints', 'zoom-in',
  'zoom-out', 'map-pin', 'calendar', 'copy', 'archive-restore', 'shield',
  'sparkle', 'shield-check', 'bookmark-check', 'log-in', 'qr-code', 'mail',
]

const pascal = (name: string) =>
  name.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase())

const entries = names.map((name) => {
  const node = (lucide as Record<string, unknown>)[pascal(name)]
  if (!Array.isArray(node)) throw new Error(`Unknown lucide icon: ${name}`)
  return `  '${name}': ${JSON.stringify(node)},`
})

await writeFile(
  new URL('../app/ui/icon-data.ts', import.meta.url),
  `// Generated by scripts/generate-icons.ts from lucide (ISC license). Do not edit.\n` +
    `export type IconNode = readonly (readonly [string, Readonly<Record<string, string>>])[]\n\n` +
    `export const iconData = {\n${entries.join('\n')}\n} satisfies Record<string, IconNode>\n\n` +
    `export type IconName = keyof typeof iconData\n`,
)
